/**
 * Experimentally determined protein structures from the RCSB Protein Data Bank.
 * Coordinates (Cα / P traces, first model) live in public/structures/<PDB>.json,
 * extracted from the deposited mmCIF files. Unlike the virus diagrams, these
 * are measured atomic models, shown at true relative size within each entry.
 */
export interface ProteinChain {
  id: string; // label_asym_id in the mmCIF
  label: string;
  host?: boolean; // a host molecule bound in the structure
  nucleic?: boolean;
}

export interface ProteinEntry {
  pdbId: string;
  virusId: string;
  name: string;
  /** Diagram component(s) this structure depicts; empty if it is not drawn in the particle diagram. */
  componentIds: string[];
  role: string;
  roleSourceIds: string[];
  method: string;
  resolutionA: number | null;
  chains: ProteinChain[];
  caveats: string[];
}

