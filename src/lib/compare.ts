import type { EvidenceStatus, Virus } from "./schema";
import { genomeClass } from "./filter";
import { formatDimension, formatKb } from "./units";

export const MAX_COMPARE = 3;
export const MIN_COMPARE = 2;

export interface CellValue {
  text: string;
  status: EvidenceStatus;
  scope: string;
  sourceIds: string[];
  note?: string;
}

export interface CompareRow {
  id: string;
  group: "Structure" | "Dimensions" | "Genome" | "Classification" | "Host" | "Replication";
  label: string;
  cells: CellValue[];
  same: boolean;
}

export interface Insight {
  kind: "similarity" | "difference" | "classification" | "uncertainty";
  text: string;
  sourceIds: string[];
}

type F = { value: unknown; status: EvidenceStatus; scope: string; sourceIds: string[]; note?: string };

function cell(f: F, text?: string): CellValue {
  const shown =
    text ??
    (f.status === "not_applicable" ? "Not applicable" : f.value === null || f.value === undefined ? "Not verified" : String(f.value));
  return { text: shown, status: f.status, scope: f.scope, sourceIds: f.sourceIds, note: f.note };
}

const yesNo = (b: unknown) => (b === true ? "Yes" : b === false ? "No" : "Not verified");

const MORPHOLOGY_LABEL: Record<string, string> = {
  "pleomorphic-enveloped": "Pleomorphic, enveloped",
  "enveloped-icosahedral-core": "Envelope around icosahedral capsid",
  "icosahedral-nonenveloped": "Icosahedral, non-enveloped",
  "head-tail": "Head–tail (tailed phage)",
  "enveloped-conical-core": "Envelope around a cone-shaped core",
  "helical-rod": "Rigid helical rod",
};
export const morphologyLabel = (m: string | null) => (m ? MORPHOLOGY_LABEL[m] ?? m : "Not verified");

export function compareRows(vs: Virus[]): CompareRow[] {
  const rows: Omit<CompareRow, "same">[] = [
    { id: "morphology", group: "Structure", label: "Virion morphology", cells: vs.map((v) => cell(v.morphology, morphologyLabel(v.morphology.value))) },
    { id: "envelope", group: "Structure", label: "Lipid envelope", cells: vs.map((v) => cell(v.envelope, yesNo(v.envelope.value))) },
    { id: "capsid", group: "Structure", label: "Capsid / nucleocapsid", cells: vs.map((v) => cell(v.capsid)) },
    {
      id: "dimensions",
      group: "Dimensions",
      label: "Measured dimensions",
      cells: vs.map((v) => {
        const primary = v.dimensions.filter((d) => d.scope !== "family" || v.dimensions.every((x) => x.scope === "family"));
        const text = primary.map((d) => `${d.label}: ${formatDimension(d)}`).join("; ");
        const statuses = primary.map((d) => d.status);
        return {
          text,
          status: statuses.includes("variable") ? "variable" : statuses[0] ?? "not_verified",
          scope: [...new Set(primary.map((d) => d.scope))].join(", "),
          sourceIds: [...new Set(primary.flatMap((d) => d.sourceIds))],
        };
      }),
    },
    { id: "nucleic", group: "Genome", label: "Genome class", cells: vs.map((v) => cell(v.genome.nucleicAcid, genomeClass(v) ?? "Not verified")) },
    { id: "sense", group: "Genome", label: "RNA sense", cells: vs.map((v) => cell(v.genome.sense)) },
    { id: "segments", group: "Genome", label: "Segments", cells: vs.map((v) => cell(v.genome.segmentCount, v.genome.segmented.value ? `Segmented (${v.genome.segmentCount.value})` : "Unsegmented")) },
    { id: "topology", group: "Genome", label: "Topology", cells: vs.map((v) => cell(v.genome.topology)) },
    { id: "length", group: "Genome", label: "Approx. genome length", cells: vs.map((v) => cell(v.genome.lengthKb, v.genome.lengthKb.value ? formatKb(v.genome.lengthKb.value) : undefined)) },
    { id: "baltimore", group: "Classification", label: "Baltimore class", cells: vs.map((v) => cell(v.baltimore, v.baltimore.value ? `Class ${v.baltimore.value}` : undefined)) },
    { id: "realm", group: "Classification", label: "ICTV realm", cells: vs.map((v) => ({ text: v.taxonomy.realm, status: "verified", scope: "species", sourceIds: v.taxonomy.sourceIds })) },
    { id: "family", group: "Classification", label: "ICTV family", cells: vs.map((v) => ({ text: v.taxonomy.family, status: "verified", scope: "species", sourceIds: v.taxonomy.sourceIds })) },
    { id: "host", group: "Host", label: "Host category", cells: vs.map((v) => cell(v.hostCategory, v.hostCategory.value ? v.hostCategory.value.charAt(0).toUpperCase() + v.hostCategory.value.slice(1) : undefined)) },
    { id: "site", group: "Replication", label: "Replication site", cells: vs.map((v) => cell(v.replication.site)) },
    { id: "mrna", group: "Replication", label: "Route to mRNA", cells: vs.map((v) => cell(v.replication.mRNARoute)) },
  ];
  return rows.map((r) => ({ ...r, same: r.cells.every((c) => c.text === r.cells[0].text) }));
}

/** Cited, rule-based statements about the selection. Nothing here is generated by AI. */
export function compareInsights(vs: Virus[]): Insight[] {
  if (vs.length < MIN_COMPARE) return [];
  const out: Insight[] = [];
  const names = (list: Virus[]) => list.map((v) => v.commonName).join(" and ");
  const all = vs.length === 2 ? "Both" : "All";
  const src = (...fs: { sourceIds: string[] }[]) => [...new Set(fs.flatMap((f) => f.sourceIds))];

  // Envelope
  const env = vs.map((v) => v.envelope.value);
  if (env.every((e) => e === env[0]) && env[0] !== null) {
    out.push({ kind: "similarity", text: `${env[0] ? `${all} are enveloped: their outer layer is a lipid membrane taken from the host cell` : `${vs.length === 2 ? "Neither has" : "None has"} a lipid envelope; the outermost layer is protein`}.`, sourceIds: src(...vs.map((v) => v.envelope)) });
  } else {
    const yes = vs.filter((v) => v.envelope.value), no = vs.filter((v) => v.envelope.value === false);
    out.push({ kind: "difference", text: `${names(yes)} ${yes.length > 1 ? "have" : "has"} a lipid envelope; ${names(no)} ${no.length > 1 ? "do" : "does"} not. An envelope is a membrane, not a protein shell, so it is not the same thing as a capsid.`, sourceIds: src(...vs.map((v) => v.envelope)) });
  }

  // Genome class + Baltimore vs ICTV (similar route, different lineage, or vice versa)
  const classes = vs.map(genomeClass);
  const balt = vs.map((v) => v.baltimore.value);
  const realms = vs.map((v) => v.taxonomy.realm);
  if (balt.every((b) => b === balt[0])) {
    const realmSame = realms.every((r) => r === realms[0]);
    out.push({
      kind: "classification",
      text: realmSame
        ? `${all} share Baltimore class ${balt[0]} and the ICTV realm ${realms[0]}. Baltimore class describes how mRNA is made; the shared realm is the separate, evolutionary claim.`
        : `${all} share Baltimore class ${balt[0]} (${classes[0]}) but sit in different ICTV realms (${[...new Set(realms)].join(", ")}). The shared genome type is a similarity of mechanism, not evidence of close common ancestry.`,
      sourceIds: src(...vs.map((v) => v.baltimore), ...vs.map((v) => v.taxonomy)),
    });
  } else {
    out.push({
      kind: "difference",
      text: `Different genome classes (${vs.map((v, i) => `${v.abbreviation}: ${classes[i]}`).join("; ")}), so each takes a different route to mRNA (Baltimore classes ${balt.join(", ")}).`,
      sourceIds: src(...vs.map((v) => v.baltimore), ...vs.map((v) => v.genome.nucleicAcid)),
    });
  }

  // Segmentation
  const seg = vs.map((v) => v.genome.segmented.value);
  if (!seg.every((s) => s === seg[0])) {
    const s = vs.filter((v) => v.genome.segmented.value);
    out.push({ kind: "difference", text: `${names(s)} ${s.length > 1 ? "split their genomes" : "splits its genome"} into separate segments; ${vs.length - s.length > 1 ? "the others carry" : "the other carries"} one molecule.`, sourceIds: src(...vs.map((v) => v.genome.segmented)) });
  }

  // Replication site
  const sites = vs.map((v) => v.replication.site.value);
  if (!sites.every((s) => s === sites[0])) {
    out.push({ kind: "difference", text: `Replication happens in different places: ${vs.map((v) => `${v.abbreviation}: ${v.replication.site.value ?? "not verified"}`).join("; ")}.`, sourceIds: src(...vs.map((v) => v.replication.site)) });
  }

  // Host
  const hosts = vs.map((v) => v.hostCategory.value);
  if (!hosts.every((h) => h === hosts[0])) {
    out.push({ kind: "difference", text: `They infect different kinds of host (${vs.map((v) => `${v.abbreviation}: ${v.hostCategory.value}`).join("; ")}).${hosts.includes("bacteria") ? " Bacterial cells have no nucleus, which constrains where a phage can replicate." : ""}`, sourceIds: src(...vs.map((v) => v.hostCategory)) });
  }

  // Uncertainty: family-level dimensions, variable morphology, unverified facts
  for (const v of vs) {
    const familyOnly = v.dimensions.length > 0 && v.dimensions.every((d) => d.scope === "family");
    if (familyOnly) out.push({ kind: "uncertainty", text: `${v.commonName}: size values are family-level ranges, not measurements of this virus specifically.`, sourceIds: src(...v.dimensions) });
    if (v.morphology.status === "variable") out.push({ kind: "uncertainty", text: `${v.commonName}: particle shape varies (${v.morphology.note ?? "pleomorphic"}).`, sourceIds: v.morphology.sourceIds });
    const unverified = v.replication.steps.filter((s) => s.status === "not_verified");
    if (unverified.length) out.push({ kind: "uncertainty", text: `${v.commonName}: ${unverified.length} replication step${unverified.length > 1 ? "s are" : " is"} shown without a verified source (${unverified.map((s) => s.title.toLowerCase()).join(", ")}).`, sourceIds: [] });
  }
  return out;
}
